export function buildPremiumReport({
  planetLongitudes = {},
  planetHouses = {},
  ascendantLongitude,
  mcLongitude,
  aspects = []
}) {
  const ascInfo = safeSign(ascendantLongitude);
  const asc = Number.isFinite(ascendantLongitude) ? {
    id: "ascendant",
    symbol: "⬆️",
    name: "Асцендент",
    area: "внешняя подача и первое впечатление",
    sign: ascInfo.sign,
    formatted: ascInfo.formatted,
    degree: ascInfo.degree,
    house: 1
  } : null;
  const mc = safeSign(mcLongitude);
  const positions = [
    asc,
    ...Object.keys(PLANET_META)
      .map(id => planetPosition(id, planetLongitudes, planetHouses))
  ].filter(Boolean);

  const p = id => getPlanet(id, planetLongitudes, planetHouses);
  const sections = {
    personality: sectionPersonality({
      sun: p("sun"), moon: p("moon"), asc, mercury: p("mercury"), aspects
    }),
    relationships: sectionRelationships({
      venus: p("venus"), mars: p("mars"), moon: p("moon"), planetHouses, aspects
    }),
    career: sectionCareer({
      sun: p("sun"), mercury: p("mercury"), mars: p("mars"), jupiter: p("jupiter"), saturn: p("saturn"), mc, planetHouses
    }),
    money: sectionMoney({
      venus: p("venus"), jupiter: p("jupiter"), saturn: p("saturn"), planetHouses
    }),
    growth: sectionGrowth({
      node: p("northNode"), saturn: p("saturn"), pluto: p("pluto"),
      uranus: p("uranus"), neptune: p("neptune"), aspects
    })
  };

  const topAspects = strongestAspects(aspects);
  const summary = [
    p("sun")?.sign && `Солнце в ${p("sun").sign}`,
    p("moon")?.sign && `Луна в ${p("moon").sign}`,
    asc?.sign && `ASC в ${asc.sign}`,
    mc?.sign && `MC в ${mc.sign}`
  ].filter(Boolean);

  return { positions, sections, topAspects, summary, mc };
}


