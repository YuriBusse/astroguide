function signInsights(sign) {
  return SIGN_INSIGHTS[cleanSign(sign)] || { plus: [], minus: [] };
}

function explainAspect(a) {
  if (!a) return "Связь показывает, как две разные части характера могут работать вместе.";
  const first = a.aName || "первая планета";
  const second = a.bName || "вторая планета";
  if (a.tone === "tense") {
    return `Здесь может возникать внутреннее противоречие: желание ${first} может идти не совсем в одном направлении с темой ${second}. В быту это иногда ощущается как «я понимаю, как надо, но внутри хочется другого». Практический способ соединить их — сначала назвать обе потребности, а затем искать действие, в котором ни одна из них не подавляется полностью.`;
  }
  return `Эти две темы карты легче соединять между собой. Поэтому качества ${first} могут поддерживать проявление темы ${second}, особенно когда вы действуете осознанно. Такой аспект полезно не просто «иметь», а переводить его в конкретную привычку или навык.`;
}

function safeSign(longitude) {
  if (!Number.isFinite(longitude)) return "—";
  return longitudeToSign(longitude);
}

function cleanSign(sign = "") {
  return sign.replace(/^[^\p{L}]*/u, "").trim();
}

function housePhrase(house) {
  return house ? HOUSE_TEXT[house] : "сферу жизни, где эта тема проявляется сильнее";
}

function planetPosition(id, planetLongitudes = {}, planetHouses = {}) {
  const longitude = planetLongitudes[id];
  if (!Number.isFinite(longitude)) return null;
  const info = safeSign(longitude);
  return {
    ...PLANET_META[id],
    id,
    sign: info.sign,
    formatted: info.formatted,
    degree: info.degree,
    house: planetHouses[id] || null
  };
}

function strongestAspects(aspects = []) {
  return [...aspects].sort((a, b) => a.orb - b.orb).slice(0, 8);
}

function aspectTone(aspect) {
  if (!aspect) return "нейтрально";
  return aspect.tone === "tense"
    ? "напряжённо: такая связь обычно показывает задачу, требующую осознанной настройки"
    : "поддерживающе: такая связь может облегчать соединение двух функций карты";
}

function getPlanet(id, longs, houses) {
  return planetPosition(id, longs, houses);
}


