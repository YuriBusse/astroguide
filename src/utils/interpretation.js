const PLANET_MEANINGS = {
  sun: "личность, воля, самоощущение и способ проявлять себя",
  moon: "эмоции, привычки, потребность в безопасности и внутренний мир",
  ascendant: "внешняя подача, первое впечатление и способ входить в новые ситуации",
  mercury: "мышление, речь, обучение и способ обрабатывать информацию",
  venus: "симпатии, отношения, вкус, ценности и способ проявлять привязанность",
  mars: "действие, энергия, инициативу, мотивацию и способ добиваться своего"
};

const PLANET_NAMES = {
  sun: "Солнце",
  moon: "Луна",
  ascendant: "Асцендент",
  mercury: "Меркурий",
  venus: "Венера",
  mars: "Марс"
};

const HOUSE_MEANINGS = {
  1: "личность, тело и способ проявлять себя",
  2: "деньги, ресурсы, самоценность и материальную опору",
  3: "общение, обучение, документы, поездки и близкое окружение",
  4: "дом, семья, корни, прошлое и внутреннее чувство опоры",
  5: "творчество, романтика, удовольствие, дети и самовыражение",
  6: "работа, режим, здоровье, навыки и повседневные обязанности",
  7: "партнёрство, отношения, брак и взаимодействие один на один",
  8: "общие ресурсы, доверие, кризисы, близость и трансформация",
  9: "образование, путешествия, мировоззрение, смысл и расширение горизонтов",
  10: "карьера, статус, цели, достижения и общественная реализация",
  11: "друзья, сообщества, планы, аудитория и долгосрочные мечты",
  12: "уединение, подсознание, восстановление, внутренний мир и завершение циклов"
};

export function buildInterpretation({ planet, sign, house, degree, data = {} }) {
  const planetName = PLANET_NAMES[planet] || planet;
  const meaning = PLANET_MEANINGS[planet] || "важная сфера личности и опыта";
  const houseMeaning = house ? HOUSE_MEANINGS[house] : "сферу жизни, где эта энергия проявляется сильнее";

  const main = data.main || `${planetName} в ${sign} показывает, как проявляются ${meaning}. В этой карте энергия положения получает дополнительный акцент через ${house ? `${house}-й дом — ${houseMeaning}` : houseMeaning}.`;
  const strengths = data.strengths || `Сильная сторона положения — использовать качества ${sign} осознанно: превращать их в конкретные решения, привычки и действия, а не оставлять только на уровне характера.`;
  const growth = data.growth || `Зона роста — не уходить в крайность качеств ${sign}. Полезно наблюдать за реакциями в напряжённых ситуациях и сознательно выбирать более гибкий способ действовать.`;
  const relationships = data.relationships || `В отношениях это положение влияет на то, как человек выражает потребности и реагирует на близость. Особенно заметно это в ситуациях, связанных с ${house ? houseMeaning : "личными границами и взаимодействием с другими"}.`;
  const career = data.career || `В реализации положение может быть полезно там, где востребованы качества ${sign}. ${house ? `При этом ${house}-й дом добавляет тему: ${houseMeaning}.` : "Лучший результат обычно появляется, когда эта энергия получает конкретную задачу и пространство для развития."}`;
  const practical = degree !== undefined && degree !== null
    ? `Точная позиция: ${degree}. В натальной карте важен не только знак, но и дом, аспекты и взаимосвязь с другими показателями. Поэтому это положение лучше рассматривать как часть общей картины, а не как отдельный диагноз характера.`
    : `Это положение стоит рассматривать вместе с домом и аспектами — именно сочетание нескольких показателей делает интерпретацию индивидуальной.`;

  return {
    planetName,
    meaning,
    houseMeaning,
    main,
    strengths,
    growth,
    relationships,
    career,
    practical
  };
}
