export function buildPlanetProfile(id, sign, house) {
  const p = PLANETS[id];
  if (!p) return null;
  const signTrait = SIGN_TRAITS[sign] || "индивидуального стиля проявления";
  const houseTopic = HOUSE_TOPICS[house] || "сферы жизни, которую показывает дом";
  const outer = ["uranus","neptune","pluto"].includes(id);
  return {
    ...p,
    main: `${p.name} в ${sign} показывает, как тема ${p.role} может проявляться через качества ${signTrait}. ${house ? `В ${house}-м доме это особенно заметно в сфере ${houseTopic}.` : ""}`,
    strengths: `В конструктивном варианте это положение помогает использовать ${signTrait} не автоматически, а как ресурс. ${house ? `Сфера ${houseTopic} может стать местом, где этот ресурс раскрывается сильнее.` : ""}`,
    growth: `Полезно следить за крайностями этого положения: любое качество может становиться слишком сильным, если использовать его без баланса. ${outer ? "Для внешних планет особенно важно смотреть на дом и аспекты к личным планетам: знак часто описывает целое поколение." : ""}`,
    practical: `${p.question} Это не отдельный «приговор» о характере: в натальной интерпретации положение читают вместе со знаком, домом и аспектами.`
  };
}

